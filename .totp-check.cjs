const { generateSecret, generateURI, generateSync, verifySync } = require('otplib');
const s = generateSecret({ length: 20 });
console.log('secret len', s.length, 'base32?', /^[A-Z2-7]+$/.test(s));
const uri = generateURI({ strategy:'totp', issuer:'NIR', label:'viewer', secret:s, algorithm:'sha1', digits:6, period:30 });
console.log('uri', uri.replace(s, s.slice(0,4)+'***'));
const tok = generateSync({ strategy:'totp', secret:s, algorithm:'sha1', digits:6, period:30 });
console.log('token', tok, 'digits', /^\d{6}$/.test(tok));
const ok = verifySync({ strategy:'totp', secret:s, token:tok, algorithm:'sha1', digits:6, period:30, epochTolerance:30 });
console.log('verify current =>', JSON.stringify(ok));
const bad = verifySync({ strategy:'totp', secret:s, token:'000000', algorithm:'sha1', digits:6, period:30, epochTolerance:30 });
console.log('verify wrong   =>', JSON.stringify(bad));
